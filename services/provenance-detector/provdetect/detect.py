"""One detection (D14). Order: a valid embedded manifest gives the definitive statement; an EXR frame is checked
through its header record against its signed sequence manifest; otherwise the picture's fingerprint (with
query variants, each in windows the signer accepts) is matched against the registry. Results are COARSE: found
or not, the basis, the provenance data, every matching manifest. Never a score, never "human-made".

Wording rules (D14): a fingerprint-only match is called AI-generated only when EVERY matching manifest has no
visual input (prompt-only outputs). Any match with a visual input reads "this video, or images or footage it
was made from, was processed by Platformless AI": a fingerprint also matches the source a clip was made from
(AP0.1b), so it never calls the file itself AI-generated or AI-modified.

What is signed is only ever: wording constants, values from a manifest that verified against the Fabstir root,
or values the signer's index returned. Nothing read from an unverified manifest or an EXR header record is
signed. A search that could not run in full (signer down or busy, the decoder refused or timed out) raises
`Unavailable` or `Unanalysable`; the API answers those unsigned, so an outage never reads as "no mark found"."""
import hashlib
import json
import time
import uuid

from . import credentials, exr, fingerprint

PROVIDER = "Fabstir Services Limited"
STATEMENT_GENERATED = "This file was generated by AI (Platformless AI, Content Credentials verified)."
STATEMENT_MODIFIED = "This file was modified by AI (Platformless AI, Content Credentials verified)."
STATEMENT_DATA = "This file is AI-generated image data (render passes) from Platformless AI (Content Credentials verified)."
# A fingerprint match is a lead, never proof: it can also hit the footage a clip was made from, and (rarely) unrelated
# low-detail footage such as credits or dark scenes (AP4 re-measurement, 2026-11-11). Only verified Content Credentials
# give a definitive statement.
STATEMENT_FP_POSSIBLE = "Possible match: this video may be, or may contain, a Platformless AI output (fingerprint match, not conclusive)."
STATEMENT_UNVERIFIED = "This file carries Platformless AI Content Credentials that could not be verified (altered or damaged)."
STATEMENT_EXR_UNVERIFIED = "This EXR frame claims Platformless AI provenance, but the claim could not be verified."
STATEMENT_EXR_MISMATCH = "This EXR frame claims Platformless AI provenance but does not match its signed frame list (altered)."
STATEMENT_UNCLASSED = "This file carries Platformless AI Content Credentials that do not say how AI was used; no statement can be made from them."
STATEMENT_OTHER_ISSUER = "This file carries Content Credentials from another issuer; no Platformless AI mark was found."
STATEMENT_NONE = "No Platformless AI mark was found. This does not show how the file was made."

DEFINITIVE = {"generated": STATEMENT_GENERATED, "modified": STATEMENT_MODIFIED, "data": STATEMENT_DATA}
HEAD_BYTES = 4 * 1024 * 1024  # sniffing and EXR headers read at most this much


class Unavailable(Exception):
    """A dependency (the signer's index or public listener) is down or busy: answer 503, unsigned."""


class Unanalysable(Exception):
    """The file cannot be analysed in full (undecodable, too long, the decoder refused or timed out): 422, unsigned."""


def sniff(b):
    if exr.is_exr(b):
        return "exr", "image/x-exr"
    if len(b) > 12 and b[4:8] == b"ftyp":
        return "video", "video/mp4"
    if b[:8] == b"\x89PNG\r\n\x1a\n":
        return "image", "image/png"
    if b[:3] == b"\xff\xd8\xff":
        return "image", "image/jpeg"
    if b[:4] == b"\x1a\x45\xdf\xa3":
        return "video", "video/webm"
    return "video", None


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _verified(s, manifests):
    return {"provider": PROVIDER, "system": s["system"], "version": s["version"], "time": s["time"], "class": s["class"], "manifests": manifests}


def _none(basis=()):
    return {"found": False, "basis": list(basis), "statement": STATEMENT_NONE, "provenance": None}


def detect(path, deps, work_dir, sha256=None, deadline=None):
    """`path`: the uploaded file inside `work_dir`. `deps`: .ffmpeg (fingerprint.Ffmpeg), .index(packed) -> [match],
    .public(path) -> bytes | None (None = not found); both raise Unavailable when the signer cannot answer.
    `deadline` (monotonic): the whole detection, every decode and every index query, finishes by then or the
    detection is Unavailable (the box is too loaded to finish a search; never a partial "no mark")."""
    with open(path, "rb") as f:
        head = f.read(HEAD_BYTES)
    if not head:
        raise Unanalysable("empty file")
    kind, mime = sniff(head)
    result = _none()

    # 1. embedded Content Credentials
    if mime and kind != "exr":
        s = credentials.read_embedded(path, mime)
        if s is not None:
            if credentials.trusted(s) and s["class"] in DEFINITIVE:
                return {"found": True, "basis": ["content_credentials"], "statement": DEFINITIVE[s["class"]], "provenance": _verified(s, [s["manifest"]])}
            if credentials.trusted(s):  # verified, but names no class we know: never defaulted to "modified"
                result.update(basis=["content_credentials_unclassed"], statement=STATEMENT_UNCLASSED)
            elif s["ours"]:  # a Fabstir signature, but the content no longer matches it
                result.update(basis=["content_credentials_invalid"], statement=STATEMENT_UNVERIFIED)
            else:  # any other signer, whatever generator name it claims
                result.update(basis=["content_credentials_other_issuer"], statement=STATEMENT_OTHER_ISSUER)

    # 2. an EXR frame: header record -> its signed sequence manifest -> the frame's hash in the index
    if kind == "exr":
        try:
            rec = exr.record(head)
        except exr.ExrError as e:
            raise Unanalysable("malformed EXR header") from e
        if rec is not None:
            return _exr(path, rec, deps, sha256 or sha256_file(path))
        return result  # a header-stripped EXR frame is not fingerprint-recognisable in v1 (plan deliverable)

    # 3. the fingerprint of the picture, with query variants, every variant in signer-sized windows
    try:
        variants = deps.ffmpeg.variants(path, work_dir, deadline)
    except fingerprint.FingerprintError as e:
        if deadline is not None and time.monotonic() >= deadline:
            raise Unavailable("out of time") from e
        raise Unanalysable(str(e)) from e
    matches = {}
    for _, packed in variants:
        for window in fingerprint.windows(packed):
            if deadline is not None and time.monotonic() >= deadline:
                raise Unavailable("out of time")
            for m in deps.index(window):
                matches[m["manifest"]] = m
    if matches:
        ms = sorted(matches.values(), key=lambda m: (m.get("time", 0), m["manifest"]))
        prov = {"provider": PROVIDER, "system": "Platformless AI", "version": None, "time": ms[0].get("time"), "class": None, "manifests": [m["manifest"] for m in ms]}
        return {"found": True, "basis": result["basis"] + ["fingerprint"], "statement": STATEMENT_FP_POSSIBLE, "provenance": prov}
    return result


def _seq_urn(rec):
    v = rec.get("sequenceManifest")
    if not isinstance(v, str) or not v.startswith("urn:c2pa:"):
        return None
    tail = v[len("urn:c2pa:") :]
    try:
        if str(uuid.UUID(tail)) != tail:
            return None
    except ValueError:
        return None
    return v


def _exr(path, rec, deps, frame_sha):
    unverified = {"found": False, "basis": ["exr_header_record"], "statement": STATEMENT_EXR_UNVERIFIED, "provenance": None}
    urn = _seq_urn(rec)
    if urn is None:
        return unverified
    seq = urn[len("urn:c2pa:") :]
    manifest = deps.public(f"/v1/manifests/{seq}")
    index = deps.public(f"/v1/manifests/{seq}/frames-index")
    if manifest is None or index is None:
        return unverified
    s = credentials.read_sidecar(manifest, index, "application/json")
    # the listener must have answered for the sequence the record names, signed by us, over this exact index
    if not credentials.trusted(s) or s["manifest"] != urn or s["class"] not in DEFINITIVE:
        return unverified
    try:
        frames = json.loads(index)["frames"]
        listed = isinstance(frames, dict) and frame_sha in set(frames.values())
    except (ValueError, KeyError, TypeError, RecursionError):
        return unverified
    if not listed:
        return {"found": False, "basis": ["exr_header_record", "sequence_manifest"], "statement": STATEMENT_EXR_MISMATCH, "provenance": None}
    return {"found": True, "basis": ["exr_header_record", "sequence_manifest"], "statement": DEFINITIVE[s["class"]], "provenance": _verified(s, [urn])}
